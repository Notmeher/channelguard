"""Fig 6 — failure gallery. Not a matplotlib figure — emits a Markdown table
with three column groups (correct blocks / false positives / misses).

Reads `paper/figures/failure_gallery.json` produced by
`infoshield.analysis.failure_cases.build` and writes
`paper/figures/failure_gallery.md`.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def _cell(text: str, max_len: int = 80) -> str:
    """Sanitize text for a Markdown table cell."""
    text = (text or "").replace("|", "\\|").replace("\n", " ").strip()
    if len(text) > max_len:
        text = text[: max_len - 1] + "…"
    return text or "—"


def _section(title: str, entries: list[dict]) -> list[str]:
    lines = [f"### {title} (n={len(entries)})", "", "| Input | Final output |", "| :--- | :--- |"]
    if not entries:
        lines.append("| _(none)_ | _(none)_ |")
    for e in entries[:10]:
        lines.append(f"| `{_cell(e.get('raw_input', ''))}` | `{_cell(e.get('final_output', ''))}` |")
    lines.append("")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default="paper/figures/failure_gallery.json")
    ap.add_argument("--out", default="paper/figures/failure_gallery.md")
    args = ap.parse_args()

    src = Path(args.json)
    if not src.exists():
        print(f"[skip] {args.json} not found; nothing to render")
        return

    data = json.loads(src.read_text(encoding="utf-8"))
    lines = ["# Failure Gallery", "",
             "Auto-generated by `figures/fig6_failure_gallery.py`.", ""]
    lines += _section("Correct blocks", data.get("correct_blocks", []))
    lines += _section("False positives", data.get("false_positives", []))
    lines += _section("Misses", data.get("misses", []))

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
