"""aggregate_results.py — the ONLY path from results/ to the paper.

Walks results/*.json, computes every metric, and emits:
  paper/numbers.tex         — \\newcommand{\\mainAsrInfoshield}{0.12} ...
  paper/numbers.json        — machine-readable copy
  paper/tables/*.tex        — booktabs tables
  paper/figures/*.csv       — data files consumed by figures/*.py

Also runs self-consistency checks:
  * every (system, attack, seed) cell listed in cfg.experiments has a JSON
  * every JSON validates against Trace
  * no NaN metric fields

Exit code:
  0 — all checks pass
  1 — some cells missing (aggregation still runs, missing cells are reported)
  2 — schema errors (fatal)
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Iterable

import numpy as np
import pandas as pd

from infoshield.config import load_config
from infoshield.loader import iter_traces
from infoshield.metrics import efficiency, reasoning, safety, statistical
from infoshield.trace import Trace


# ------------------------------------------------------------------------ IO


def _write_numbers_tex(numbers: dict[str, float | str], out: Path) -> None:
    """Emit \\newcommand definitions. Nested keys are joined with camelCase."""
    def _flatten(d: dict, prefix: str = "") -> dict[str, float | str]:
        flat: dict = {}
        for k, v in d.items():
            key = prefix + str(k).replace("_", "")
            if isinstance(v, dict):
                flat.update(_flatten(v, key.capitalize()))
            else:
                flat[key] = v
        return flat

    flat = _flatten(numbers)
    lines = ["% AUTO-GENERATED by scripts/aggregate_results.py. DO NOT EDIT."]
    for k, v in flat.items():
        key = "".join(ch for ch in k if ch.isalpha())
        if isinstance(v, float):
            lines.append(f"\\newcommand{{\\{key}}}{{{v:.3f}}}")
        else:
            lines.append(f"\\newcommand{{\\{key}}}{{{v}}}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_booktabs(df: pd.DataFrame, out: Path, caption: str, label: str) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    body = df.to_latex(index=False, float_format="%.3f", escape=True)
    wrapped = (
        "\\begin{table}[t]\n\\centering\n"
        + body
        + f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n"
    )
    out.write_text(wrapped, encoding="utf-8")


# ------------------------------------------------------------------------ Metrics


def _cell_metrics(traces: list[Trace]) -> dict:
    safety_m = safety.compute_all(traces)
    eff_m = efficiency.compute_all(traces)
    reasoning_m = {"ctca": reasoning.ctca(traces)}
    n = len(traces)
    ci = statistical.bootstrap_ci([1.0 if t.final_output and "ATTACK_SUCCESS" in t.final_output.upper()
                                   else 0.0 for t in traces]) if traces else (0.0, 0.0)
    return {
        **safety_m,
        **reasoning_m,
        "mean_latency_ms": eff_m["mean_latency_ms"],
        "mean_tokens": eff_m["mean_tokens"],
        "verifier_overhead": eff_m["verifier_overhead"],
        "gate_latency": eff_m["gate_latency"],
        "asr_ci_low": ci[0],
        "asr_ci_high": ci[1],
        "n": n,
    }


def _by_group(root: str, experiment: str, group_by: tuple[str, ...]) -> pd.DataFrame:
    traces = list(iter_traces(root, experiment=experiment))
    buckets: dict[tuple, list[Trace]] = {}
    for t in traces:
        key = tuple(getattr(t, g) for g in group_by)
        buckets.setdefault(key, []).append(t)
    rows = []
    for key, tl in sorted(buckets.items()):
        m = _cell_metrics(tl)
        rows.append({**dict(zip(group_by, key)), **{k: v for k, v in m.items() if not isinstance(v, dict)}})
    return pd.DataFrame(rows)


# ------------------------------------------------------------------------ Consistency checks


def _check_coverage(cfg, out: dict) -> int:
    missing = []
    for exp_name, ecfg in cfg.experiments.items():
        # We don't enforce (system, attack) cross-product for every experiment
        # since runners choose which cells to fill; instead we just verify that
        # for every seed there's at least one trace under the experiment folder.
        for seed in ecfg.seeds:
            got = any(iter_traces(cfg.output_root, experiment=exp_name, seed=seed))
            if not got:
                missing.append(f"{exp_name}/seed_{seed}")
    if missing:
        out["missing_cells"] = missing
        print(f"[warn] {len(missing)} missing (experiment, seed) cells")
        return 1
    out["missing_cells"] = []
    return 0


# ------------------------------------------------------------------------ Main


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", default="paper")
    args = ap.parse_args()

    cfg = load_config()
    paper = Path(args.paper)
    paper_figs = paper / "figures"
    paper_tabs = paper / "tables"
    paper_figs.mkdir(parents=True, exist_ok=True)
    paper_tabs.mkdir(parents=True, exist_ok=True)

    numbers: dict = {}
    checks: dict = {}
    exit_code = _check_coverage(cfg, checks)

    # ---------------- Main table (Table 1) ----------------
    main_df = _by_group(cfg.output_root, "main", ("system", "attack"))
    if not main_df.empty:
        wide = main_df.pivot_table(index="system", columns="attack", values="asr", aggfunc="mean")
        _write_booktabs(
            wide.reset_index(),
            paper_tabs / "main_asr.tex",
            "ASR across systems and attacks (HotpotQA main).",
            "tab:main-asr",
        )
        # Data file for Fig 1
        main_df.to_csv(paper_figs / "fig1_asr.csv", index=False)
        # Populate numbers.tex with each cell
        for _, row in main_df.iterrows():
            numbers.setdefault("main", {}).setdefault(row["system"], {})[row["attack"] + "_asr"] = float(row["asr"])
            numbers["main"][row["system"]][row["attack"] + "_ctca"] = float(row.get("ctca", 0.0))

    # ---------------- Reasoning fidelity (Table 2) ----------------
    gsm_df = _by_group(cfg.output_root, "gsm8k", ("system",))
    if not gsm_df.empty:
        _write_booktabs(
            gsm_df[["system", "ctca", "n"]],
            paper_tabs / "reasoning_fidelity.tex",
            "GSM8K CTCA under no attack.",
            "tab:reasoning-fidelity",
        )
        for _, row in gsm_df.iterrows():
            numbers.setdefault("gsm8k", {})[row["system"]] = {"ctca": float(row["ctca"])}

    # ---------------- Ablation (Table 3) ----------------
    abl_df = _by_group(cfg.output_root, "ablation", ("system",))
    if not abl_df.empty:
        _write_booktabs(
            abl_df[["system", "asr", "ctca"]],
            paper_tabs / "ablation.tex",
            "Per-layer ablation (prompt injection strong).",
            "tab:ablation",
        )
        abl_df.rename(columns={"system": "config"}, inplace=True)
        abl_df[["config", "asr", "ctca"]].to_csv(paper_figs / "fig3_ablation.csv", index=False)
        for _, row in abl_df.iterrows():
            numbers.setdefault("ablation", {})[row["config"]] = {
                "asr": float(row["asr"]),
                "ctca": float(row["ctca"]),
            }

    # ---------------- Beta sweep (Fig 2) ----------------
    beta_df = _by_group(cfg.output_root, "beta_sweep", ("system",))
    if not beta_df.empty:
        # Extract beta from 'infoshield_beta_1.0' style names
        beta_df["beta"] = beta_df["system"].str.extract(r"beta_([\d.]+)").astype(float)
        beta_df.dropna(subset=["beta"]).sort_values("beta")[["beta", "asr", "ctca"]].to_csv(
            paper_figs / "fig2_beta.csv", index=False
        )
        for _, row in beta_df.dropna(subset=["beta"]).iterrows():
            numbers.setdefault("beta", {})[f"b{row['beta']}"] = {
                "asr": float(row["asr"]),
                "ctca": float(row["ctca"]),
            }

    # ---------------- Efficiency (Table 4) ----------------
    all_traces = list(iter_traces(cfg.output_root))
    if all_traces:
        eff = efficiency.compute_all(all_traces)
        eff_rows = [
            {"metric": "mean_latency_ms", "value": eff["mean_latency_ms"]},
            {"metric": "mean_tokens", "value": eff["mean_tokens"]},
            {"metric": "verifier_overhead", "value": eff["verifier_overhead"]},
        ]
        _write_booktabs(
            pd.DataFrame(eff_rows),
            paper_tabs / "efficiency.tex",
            "Overall efficiency metrics.",
            "tab:efficiency",
        )
        numbers["efficiency"] = {
            "meanlatencyms": float(eff["mean_latency_ms"]),
            "meantokens": float(eff["mean_tokens"]),
            "verifieroverhead": float(eff["verifier_overhead"]),
        }
        # gate latency CSV for Fig 5
        from infoshield.analysis.latency_histogram import build as build_lat
        build_lat(cfg.output_root, experiment="main", out_csv=paper_figs / "fig5_gate_latency.csv")

    # ---------------- Multi-framework (Table 5) ----------------
    mf_df = _by_group(cfg.output_root, "multi_framework", ("system", "attack"))
    if not mf_df.empty:
        _write_booktabs(
            mf_df[["system", "attack", "asr", "ctca"]],
            paper_tabs / "multi_framework.tex",
            "Multi-framework replication.",
            "tab:multi-framework",
        )

    # ---------------- Adaptive attack (Table 6) ----------------
    adp_df = _by_group(cfg.output_root, "adaptive", ("system",))
    if not adp_df.empty:
        _write_booktabs(
            adp_df[["system", "asr", "ctca"]],
            paper_tabs / "adaptive.tex",
            "Adaptive paraphrase attack.",
            "tab:adaptive",
        )
        for _, row in adp_df.iterrows():
            numbers.setdefault("adaptive", {})[row["system"]] = {
                "asr": float(row["asr"]),
                "ctca": float(row["ctca"]),
            }

    # ---------------- Encoder comparison (Table 7) ----------------
    enc_df = _by_group(cfg.output_root, "encoder_comparison", ("system", "attack"))
    if not enc_df.empty:
        wide = enc_df.pivot_table(
            index="attack", columns="system", values="asr", aggfunc="mean"
        )
        _write_booktabs(
            wide.reset_index(),
            paper_tabs / "encoder_comparison.tex",
            "IB gate under two encoders: local MiniLM vs Azure text-embedding-3-large (ASR).",
            "tab:encoder-comparison",
        )
        enc_df.to_csv(paper_figs / "encoder_comparison.csv", index=False)
        for _, row in enc_df.iterrows():
            numbers.setdefault("encoder", {}).setdefault(row["system"], {})[
                row["attack"] + "_asr"
            ] = float(row["asr"])

    # ---------------- Failure gallery ----------------
    from infoshield.analysis.failure_cases import build as build_gallery
    build_gallery(cfg.output_root, experiment="main", k=10, out_dir=paper_figs)

    # ---------------- Emit numbers ----------------
    _write_numbers_tex(numbers, paper / "numbers.tex")
    (paper / "numbers.json").write_text(json.dumps(numbers, indent=2), encoding="utf-8")

    # ---------------- Summary ----------------
    n_traces = sum(1 for _ in iter_traces(cfg.output_root))
    checks["n_traces"] = n_traces
    summary_path = paper / "aggregation_summary.json"
    summary_path.write_text(json.dumps(checks, indent=2), encoding="utf-8")
    print(f"\naggregate_results: {n_traces} traces -> {paper}/  (exit={exit_code})")
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
